// ── CSV (jsreport render path, recipe 'text') ───────────────────────────────
//
// Mirrors report-journal-entries-show-options.test.js: builds the helpers
// string the same way report-api.js does for jsreport (canonical set +
// report-specific `csvField` extracted from helpers.js), evaluates it via
// `new Function`, and registers on a fresh Handlebars instance.

function renderCsv(rows, locale = 'en_US') {
  const built = buildJsreportHelpersString(HELPERS_CODE);
  const helperNames = [...built.matchAll(/^function\s+(\w+)\s*\(/gm)].map((m) => m[1]);
  // eslint-disable-next-line no-new-func
  const helpers = new Function(`${built}\nreturn { ${helperNames.join(', ')} };`)();

  const hb = Handlebars.create();
  for (const [name, fn] of Object.entries(helpers)) {
    hb.registerHelper(name, fn);
  }
  const templateSrc = readFileSync(resolve(ARTIFACT_DIR, 'template-csv.hbs'), 'utf8');
  const template = hb.compile(templateSrc);
  return template({
    meta: { ...META_BASE, labels: LABELS[locale] },
    rows,
  });
}

describe('tax-report — template-csv.hbs', () => {
  it('escapes a contact name with an embedded comma and double quote (real quoting, no &quot; leak)', () => {
    const csv = renderCsv(ROWS_DETAIL);
    assert.match(csv, /"Proveedor, SA ""grande"""/, 'expected doubled internal quotes, wrapped in quotes');
    assert.doesNotMatch(csv, /&quot;/, 'csvField output must never be HTML-escaped — the template must use {{{ }}}, not {{ }}');
  });

  it('includes both the ungrouped (docs) and grouped-by-bp (bpGroups.docs) rows', () => {
    const csv = renderCsv(ROWS_DETAIL);
    assert.match(csv, /INV-001/);
    assert.match(csv, /ARI-002/);
    assert.match(csv, /VAT 21% \(ungrouped\)/);
    assert.match(csv, /VAT 10% \(grouped\)/);
  });

  it('formats dates via formatDateDisplay (dd-mm-yyyy) and prints raw (unformatted) amounts', () => {
    const csv = renderCsv(ROWS_DETAIL);
    assert.match(csv, /01-08-2026/); // docDate 2026-08-01 -> dd-mm-yyyy
    assert.match(csv, /02-08-2026/); // acctDate 2026-08-02
    assert.match(csv, /100\.5/);
    assert.doesNotMatch(csv, /100,5/, 'amounts must never go through formatCurrency in the CSV export');
  });

  it('exports ONLY the Detail data — no Summary-by-Category or Summary-by-Rate content', () => {
    const rowsWithSummaries = {
      ...ROWS_DETAIL,
      purchase: {
        ...ROWS_DETAIL.purchase,
        summaryByCategory: [{ taxCategoryId: 'cat-x', taxCategoryName: 'SHOULD_NOT_APPEAR_CATEGORY', taxes: [] }],
        summaryByRate: [{ rate: 21, bpGroups: [{ bPartnerId: 'bp-x', bPartner: 'SHOULD_NOT_APPEAR_BP', bpTaxId: 'SHOULD_NOT_APPEAR_TAXID', taxes: [] }] }],
      },
    };
    const csv = renderCsv(rowsWithSummaries);
    assert.doesNotMatch(csv, /SHOULD_NOT_APPEAR/);
  });

  it('header row uses translated labels [es_ES]', () => {
    const csv = renderCsv(ROWS_DETAIL, 'es_ES');
    assert.match(csv, /^Tipo de Transacción,Impuesto,Nº Doc\.,Tipo Doc\.,Fecha Doc\.,Fecha Contable,Contacto,País,Región,Base Imponible,Importe Impuesto,Importe Total/m);
  });

  it('header row uses translated labels [en_US]', () => {
    const csv = renderCsv(ROWS_DETAIL, 'en_US');
    assert.match(csv, /^Transaction Type,Tax Name,Doc No\.,Doc Type,Doc Date,Acct Date,Contact,Country,Region,Tax Base,Tax Amount,Total/m);
  });
});
