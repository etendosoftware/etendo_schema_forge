// ETP-4899 — tax-report Excel/CSV export templates.
//
// tax-report is `"source": "neo"` (handler-driven, TaxReportHandler.java) and,
// until this change, reused template.hbs (the HTML/PDF template — grouped
// bands, blank filler cells, formatted text) for the Excel export too: every
// cell in the resulting .xlsx (including amounts) rendered as text (`t="str"`),
// not calculable. template-excel.hbs/template-csv.hbs fix this by dumping one
// flat, denormalized row per document, with `data-cell-type="number"` +
// unformatted values for amounts (verified against a real jsreport container
// to render `t="n"` numeric cells — see artifacts/tax-report/template-excel.hbs
// header comment).
//
// These tests compile the REAL .hbs files from disk (never a hardcoded copy)
// so a future edit that reintroduces text-typed amounts, or breaks the
// denormalization path (1-level-up `../taxName` for ungrouped docs vs.
// 2-levels-up `../../taxName` for grouped-by-contact docs, and the
// `../../rate` / `../bPartner` / `../bpTaxId` relative paths in the
// Summary-by-Rate sheet), fails here.

