function renderExcel(rows, locale = 'en_US') {
  const hb = Handlebars.create();
  registerReportHelpers(hb, HELPERS_CODE);
  const templateSrc = readFileSync(resolve(ARTIFACT_DIR, 'template-excel.hbs'), 'utf8');
  const template = hb.compile(templateSrc);
  return template({
    css: '',
    meta: { ...META_BASE, labels: LABELS[locale] },
    rows,
  });
}

describe('tax-report — template-excel.hbs — Sheet 1 (Detail)', () => {
  for (const locale of ['en_US', 'es_ES']) {
    it(`denormalizes taxName from 1 level up (taxGroup.docs, groupByBp=false) and labels the row correctly [${locale}]`, () => {
      const html = renderExcel(ROWS_DETAIL, locale);
      const rowIdx = html.indexOf('INV-001');
      assert.ok(rowIdx !== -1, 'expected the ungrouped doc row to be present');
      const row = html.slice(html.lastIndexOf('<tr>', rowIdx), html.indexOf('</tr>', rowIdx));
      assert.match(row, /VAT 21% \(ungrouped\)/, 'taxName must be denormalized from the parent taxGroup');
      assert.match(row, new RegExp(LABELS[locale].purchasesPayments.replace(/[/]/g, '\\/')));
    });

    it(`denormalizes taxName from 2 levels up (taxGroup.bpGroups[].docs, groupByBp=true) and labels the row correctly [${locale}]`, () => {
      const html = renderExcel(ROWS_DETAIL, locale);
      const rowIdx = html.indexOf('ARI-002');
      assert.ok(rowIdx !== -1, 'expected the grouped-by-bp doc row to be present');
      const row = html.slice(html.lastIndexOf('<tr>', rowIdx), html.indexOf('</tr>', rowIdx));
      assert.match(row, /VAT 10% \(grouped\)/, 'taxName must be denormalized from 2 levels up (taxGroup, not bpGroup)');
      assert.match(row, new RegExp(LABELS[locale].salesReceipts.replace(/[/]/g, '\\/')));
    });

    it(`amount cells are numeric (data-cell-type="number") with RAW unformatted values [${locale}]`, () => {
      const html = renderExcel(ROWS_DETAIL, locale);
      // Raw dot-decimal, never the es-ES-formatted "100,50".
      assert.match(html, /<td data-cell-type="number">100\.5<\/td>/);
      assert.match(html, /<td data-cell-type="number">21\.1<\/td>/);
      assert.match(html, /<td data-cell-type="number">121\.6<\/td>/);
      assert.doesNotMatch(html, /100,5/, 'amounts must never go through formatCurrency (es-ES comma decimal)');
    });
  }
});

