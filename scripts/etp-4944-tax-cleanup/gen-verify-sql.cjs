#!/usr/bin/env node
// ETP-4944 — Task 6: generate the post-apply verification queries
// (verify.sql) from resolved-scope.json. Same convention as
// gen-delete-sql.cjs: ids are never hand-typed, always read from the
// generated scope file.
//
// Checks:
//   1. Orphan checks (obtl_tax_parameter / c_tax_zone / c_tax.parent_tax_id)
//      — generic, environment-independent (any dangling FK is a bug
//      regardless of which ids this environment actually deleted).
//   2. Record-count reconciliation (system-level c_tax rows).
//   3. Every id in `deactivateIds` (103: 102 static sibling-overlap + IVA
//      Normal) must show isactive='N' AND description='Discarded Tax for
//      EtendoGO' EXACTLY — not just isactive.
//   4. Every id in `deleteIds` (144) must be fully gone from c_tax AND from
//      every dependent table (zero remaining dependents), confirming the
//      dynamic try-delete path actually deleted them on THIS environment
//      rather than silently falling back to deactivate.
const fs = require('fs');
const path = require('path');
const scope = JSON.parse(fs.readFileSync(path.join(__dirname, 'resolved-scope.json'), 'utf8'));
const deleteIds = scope.deleteIds; // 144 — expected fully deleted (CSV-scoped, not sibling-overlap)
const deactivateIds = scope.deactivateIds; // 103 — expected isactive='N' + discarded description
const DISCARDED_DESCRIPTION = 'Discarded Tax for EtendoGO';
const esc = s => s.replace(/'/g, "''");
const pgList = ids => ids.map(id => `'${id}'`).join(',');

const lines = [];
lines.push('-- ============================================================================');
lines.push('-- ETP-4944 — Post-apply verification (Task 6). Generated by gen-verify-sql.cjs');
lines.push('-- from resolved-scope.json — DO NOT edit by hand. Run AFTER');
lines.push('-- 01-apply-tax-cleanup.sql has been applied with -v do_commit=1.');
lines.push('-- Read-only: no writes, safe to re-run any number of times.');
lines.push('-- ============================================================================');
lines.push('\\set ON_ERROR_STOP on');
lines.push('');
lines.push('-- ---------------------------------------------------------------------------');
lines.push('-- Step 1: Orphan checks (AC "no orphaned OBTL_Tax_Parameter", extended to the');
lines.push('-- other two FK-shaped tables this plan found undocumented in the ticket).');
lines.push('-- ---------------------------------------------------------------------------');
lines.push("\\echo 'Orphaned obtl_tax_parameter (expect 0):'");
lines.push('SELECT count(*) FROM obtl_tax_parameter otp');
lines.push('  LEFT JOIN c_tax t ON t.c_tax_id = otp.c_tax_id');
lines.push('  WHERE t.c_tax_id IS NULL;');
lines.push("\\echo 'Orphaned c_tax_zone (expect 0):'");
lines.push('SELECT count(*) FROM c_tax_zone z');
lines.push('  LEFT JOIN c_tax t ON t.c_tax_id = z.c_tax_id');
lines.push('  WHERE t.c_tax_id IS NULL;');
lines.push("\\echo 'Orphaned c_tax.parent_tax_id (expect 0):'");
lines.push('SELECT count(*) FROM c_tax c');
lines.push('  LEFT JOIN c_tax p ON p.c_tax_id = c.parent_tax_id');
lines.push('  WHERE c.parent_tax_id IS NOT NULL AND p.c_tax_id IS NULL;');
lines.push('');
lines.push('-- ---------------------------------------------------------------------------');
lines.push('-- Step 2: Record-count reconciliation (sanity check on the whole operation).');
lines.push(`-- Expect ${653 - deleteIds.length} = ${scope.sourceXmlRecordCount} (source XML) - ${deleteIds.length} (real deletes);`);
lines.push('-- deactivated ids are NOT subtracted — they survive as inactive rows.');
lines.push('-- ---------------------------------------------------------------------------');
lines.push(`\\echo 'System-level c_tax rows (expect ${scope.sourceXmlRecordCount - deleteIds.length}):'`);
lines.push("SELECT count(*) FROM c_tax WHERE ad_client_id = '0';");
lines.push('');
lines.push('-- ---------------------------------------------------------------------------');
lines.push(`-- Step 3: Deactivated ids (${deactivateIds.length}) must show isactive='N' AND`);
lines.push(`-- description='${DISCARDED_DESCRIPTION}' EXACTLY, not just isactive.`);
lines.push('-- ---------------------------------------------------------------------------');
lines.push(`\\echo 'Deactivated ids (${deactivateIds.length}) NOT matching isactive=N + discarded description (expect 0):'`);
lines.push('SELECT count(*) FROM c_tax');
lines.push(`  WHERE c_tax_id IN (${pgList(deactivateIds)})`);
lines.push(`    AND ad_client_id = '0'`);
lines.push(`    AND NOT (isactive = 'N' AND description = '${esc(DISCARDED_DESCRIPTION)}');`);
lines.push(`\\echo 'Deactivated ids (${deactivateIds.length}) missing entirely from c_tax (expect 0 — they must survive, just inactive):'`);
lines.push('SELECT count(*) FROM (');
lines.push(`  SELECT unnest(ARRAY[${pgList(deactivateIds)}]) AS c_tax_id`);
lines.push(') expected');
lines.push('LEFT JOIN c_tax t ON t.c_tax_id = expected.c_tax_id AND t.ad_client_id = \'0\'');
lines.push('WHERE t.c_tax_id IS NULL;');
lines.push('');
lines.push('-- ---------------------------------------------------------------------------');
lines.push(`-- Step 4: Deleted ids (${deleteIds.length}) must be fully gone from c_tax AND`);
lines.push('-- have zero remaining dependents in every FK-dependent table.');
lines.push('-- ---------------------------------------------------------------------------');
lines.push(`\\echo 'Deleted ids (${deleteIds.length}) still present in c_tax (expect 0):'`);
lines.push(`SELECT count(*) FROM c_tax WHERE c_tax_id IN (${pgList(deleteIds)}) AND ad_client_id = '0';`);
lines.push(`\\echo 'Deleted ids (${deleteIds.length}) with remaining obtl_tax_parameter dependents (expect 0):'`);
lines.push(`SELECT count(*) FROM obtl_tax_parameter WHERE c_tax_id IN (${pgList(deleteIds)});`);
lines.push(`\\echo 'Deleted ids (${deleteIds.length}) with remaining c_tax_zone dependents (expect 0):'`);
lines.push(`SELECT count(*) FROM c_tax_zone WHERE c_tax_id IN (${pgList(deleteIds)});`);
lines.push(`\\echo 'Deleted ids (${deleteIds.length}) with remaining c_tax_trl dependents (expect 0):'`);
lines.push(`SELECT count(*) FROM c_tax_trl WHERE c_tax_id IN (${pgList(deleteIds)});`);
lines.push(`\\echo 'Deleted ids (${deleteIds.length}) with remaining c_tax_acct dependents (expect 0):'`);
lines.push(`SELECT count(*) FROM c_tax_acct WHERE c_tax_id IN (${pgList(deleteIds)});`);
lines.push(`\\echo 'Deleted ids (${deleteIds.length}) still referenced as some row\\'s parent_tax_id (expect 0):'`);
lines.push(`SELECT count(*) FROM c_tax WHERE parent_tax_id IN (${pgList(deleteIds)});`);
lines.push('');
lines.push('-- ---------------------------------------------------------------------------');
lines.push('-- Step 5: MODIFY rename applied correctly.');
lines.push('-- ---------------------------------------------------------------------------');
lines.push(`\\echo 'MODIFY id ${scope.modify.id} name/description correctly renamed (expect 1):'`);
lines.push(`SELECT count(*) FROM c_tax WHERE c_tax_id = '${scope.modify.id}' AND ad_client_id = '0'`);
lines.push(`  AND name = '${esc(scope.modify.newName)}' AND description = '${esc(scope.modify.newName)}';`);
lines.push(`\\echo 'MODIFY id ${scope.modify.id} c_tax_trl correctly renamed (expect 1):'`);
lines.push(`SELECT count(*) FROM c_tax_trl WHERE c_tax_id = '${scope.modify.id}' AND name = '${esc(scope.modify.newName)}';`);

fs.writeFileSync(path.join(__dirname, 'verify.sql'), lines.join('\n') + '\n');
console.log('Wrote', path.join(__dirname, 'verify.sql'), `(${deleteIds.length} delete ids, ${deactivateIds.length} deactivate ids checked)`);
