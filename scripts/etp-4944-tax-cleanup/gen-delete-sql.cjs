#!/usr/bin/env node
// ETP-4944 — Generate the companion SQL data-fix for already-provisioned
// environments. Same dry-run/commit convention as scripts/etp-4177-tax-migration.
//
// NOTE (deviation from the plan's literal table name, confirmed 2026-09-03
// against the local dev DB via `ad_table`/`pg_tables`): the physical table
// backing FinancialMgmtTaxZone is `c_tax_zone` (with an underscore between
// "tax" and "zone"), NOT `c_taxzone` as originally guessed in the plan. All
// other table/column names (`c_tax`, `c_tax_trl`, `obtl_tax_parameter`,
// `c_tax_id`, `parent_tax_id`, `ad_client_id`) were confirmed correct as-is.
//
// NOTE (real gap found empirically 2026-09-03, dry-run against local dev DB):
// `c_tax_acct` (per-client, per-account-schema tax accounting setup) is a
// 4th FK-dependent table the plan never accounted for — it isn't part of
// the reference-data XML at all (0 hits, confirmed by grep), so Task 3's
// transform doesn't need it, but it DOES hold a live FK to c_tax and is
// populated per client as a byproduct of account-schema setup (not "real
// document usage" the way c_invoiceline/c_orderline etc. are — see
// 00-assess-usage.sql candidates). The first real dry-run against the local
// dev DB failed with `c_tax_acct_c_tax` FK violation before this was added.
// Every client that has ever set up an accounting schema accumulates one
// c_tax_acct row per system tax rate, so this delete is expected to hit
// every client, not just client '0'.
const fs = require('fs');
const path = require('path');
const scope = JSON.parse(fs.readFileSync(path.join(__dirname, 'resolved-scope.json'), 'utf8'));
const ids = scope.deleteIds;
const inList = ids.map(id => `'${id}'`).join(',');
const { id: modId, newName } = scope.modify;
const esc = s => s.replace(/'/g, "''");

const lines = [];
lines.push('-- ============================================================================');
lines.push('-- ETP-4944 — Apply Spanish fiscal tax rate cleanup (already-provisioned envs)');
lines.push('-- Generated by gen-delete-sql.cjs from resolved-scope.json — DO NOT edit by hand.');
lines.push('-- Dry-run by default; -v do_commit=1 to apply. Run 00-assess-usage.sql FIRST.');
lines.push('-- ============================================================================');
lines.push('\\set ON_ERROR_STOP on');
lines.push('\\if :{?do_commit} \\else \\set do_commit 0 \\endif');
lines.push('BEGIN;');
lines.push('SELECT ad_disable_triggers();');
lines.push('');
lines.push(`-- Repoint any surviving child's parent before deleting the parent rows`);
for (const [childId, newParentId] of Object.entries(scope.parentRepoints || {})) {
  lines.push(`UPDATE c_tax SET parent_tax_id = ${newParentId ? `'${newParentId}'` : 'NULL'} WHERE c_tax_id = '${childId}';`);
}
lines.push('');
lines.push(`-- Dependents first (FK order), then the tax rate rows themselves`);
lines.push(`DELETE FROM obtl_tax_parameter WHERE c_tax_id IN (${inList});`);
lines.push(`DELETE FROM c_tax_zone WHERE c_tax_id IN (${inList});`);
lines.push(`DELETE FROM c_tax_trl WHERE c_tax_id IN (${inList});`);
lines.push(`-- c_tax_acct: per-client tax accounting setup, not reference data (not in`);
lines.push(`-- the XML) — but still FK's to c_tax across every client that has ever`);
lines.push(`-- initialized an account schema, so it must be cleared before c_tax itself.`);
lines.push(`DELETE FROM c_tax_acct WHERE c_tax_id IN (${inList});`);
lines.push(`DELETE FROM c_tax WHERE c_tax_id IN (${inList}) AND ad_client_id = '0';`);
lines.push('');
lines.push(`-- MODIFY: rename ${modId}`);
lines.push(`UPDATE c_tax SET name = '${esc(newName)}', description = '${esc(newName)}' WHERE c_tax_id = '${modId}' AND ad_client_id = '0';`);
lines.push(`UPDATE c_tax_trl SET name = '${esc(newName)}' WHERE c_tax_id = '${modId}';`);
lines.push('');
lines.push('SELECT ad_enable_triggers();');
lines.push("\\echo ''");
lines.push("\\echo 'Remaining c_tax rows at client 0 matching the delete list (expect 0):'");
lines.push(`SELECT count(*) FROM c_tax WHERE c_tax_id IN (${inList}) AND ad_client_id = '0';`);
lines.push('\\if :do_commit');
lines.push("  \\echo '>>> do_commit=1 : COMMITTING.'");
lines.push('  COMMIT;');
lines.push('\\else');
lines.push("  \\echo '>>> dry run : ROLLING BACK. Re-run with -v do_commit=1 to apply.'");
lines.push('  ROLLBACK;');
lines.push('\\endif');

const out = path.join(__dirname, '01-apply-tax-cleanup.sql');
fs.writeFileSync(out, lines.join('\n') + '\n');
console.log('Wrote', out, `(${ids.length} delete ids, 1 rename)`);
