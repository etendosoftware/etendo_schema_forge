#!/usr/bin/env node
// ETP-4944 — Generate the companion SQL data-fix for already-provisioned
// environments (01-apply-tax-cleanup.sql), plus the belt-and-suspenders
// read-only usage check (00-assess-usage.sql). Same dry-run/commit
// convention as scripts/etp-4177-tax-migration.
//
// NOTE (deviation from the plan's literal table name, confirmed 2026-09-03
// against the local dev DB via `ad_table`/`pg_tables`): the physical table
// backing FinancialMgmtTaxZone is `c_tax_zone` (with an underscore between
// "tax" and "zone"), NOT `c_taxzone` as originally guessed in the plan. All
// other table/column names (`c_tax`, `c_tax_trl`, `obtl_tax_parameter`,
// `c_tax_id`, `parent_tax_id`, `ad_client_id`) were confirmed correct as-is.
//
// NOTE (real gap found empirically 2026-09-03, dry-run against local dev DB):
// `c_tax_acct` (per-client, per-account-schema tax accounting setup) is a
// 4th FK-dependent table the plan never accounted for — it isn't part of
// the reference-data XML at all (0 hits, confirmed by grep), so Task 3's
// transform doesn't need it, but it DOES hold a live FK to c_tax and is
// populated per client as a byproduct of account-schema setup. Every client
// that has ever set up an accounting schema accumulates one c_tax_acct row
// per system tax rate, so this delete is expected to hit every client, not
// just client '0'.
//
// NOTE (reporter's environment-agnostic correction, 2026-09-03 rework): a
// FIXED delete/deactivate id split derived from local dev's own FK data is
// NOT safe to ship — a different environment can have different live
// references among the 145 delete-attempt candidates. So this generator no
// longer pre-classifies those 145 into delete vs. deactivate buckets; it
// only knows two things ahead of time:
//   - staticDeactivateIds (102): the sibling-AEAT-module-overlap ids. These
//     are environment-independent (derived from the 3 sibling modules' own
//     shipped reference-data files, not from any DB's content) — never
//     attempted as a delete, anywhere, ever.
//   - candidateIds (145): every id CSV-scoped for deletion (144) plus IVA
//     Normal (folded in generically now, no longer special-cased) — each is
//     tried as a real cascade delete inside a PL/pgSQL exception handler; a
//     foreign_key_violation on a given id falls back to deactivating THAT id
//     only. The classification of which of the 145 actually got deleted vs.
//     deactivated is decided at RUNTIME, per environment, and only exists as
//     this script's own `etp4944_outcome` temp-table output — it is
//     deliberately NOT a build-time artifact of resolved-scope.json anymore.
// This also makes the script naturally idempotent: re-running it against an
// environment that already applied it just deletes 0 rows / re-sets
// isactive='N' on an already-inactive row, with no error either way.
const fs = require('fs');
const path = require('path');
const scope = JSON.parse(fs.readFileSync(path.join(__dirname, 'resolved-scope.json'), 'utf8'));
const candidateIds = scope.candidateIds; // 145: attempt delete, dynamic per-environment fallback
const staticDeactivateIds = scope.staticDeactivateIds; // 102: always deactivate, never attempted as delete
const { id: modId, newName } = scope.modify;
const esc = s => s.replace(/'/g, "''");
const DISCARDED_DESCRIPTION = 'Discarded Tax for EtendoGO'; // reporter's exact wording — do not translate/rephrase
const pgArray = ids => 'ARRAY[' + ids.map(id => `'${id}'`).join(',') + ']::varchar(32)[]';

const lines = [];
lines.push('-- ============================================================================');
lines.push('-- ETP-4944 — Apply Spanish fiscal tax rate cleanup (already-provisioned envs)');
lines.push('-- Generated by gen-delete-sql.cjs from resolved-scope.json — DO NOT edit by hand.');
lines.push('-- Dry-run by default; -v do_commit=1 to apply. Run 00-assess-usage.sql FIRST.');
lines.push('--');
lines.push('-- Environment-agnostic & idempotent by design: the 102 sibling-module-overlap');
lines.push('-- ids always deactivate (static, same everywhere). Every other candidate id is');
lines.push('-- tried as a real delete and falls back to deactivating THAT id only on an');
lines.push('-- actual foreign_key_violation, decided against THIS environment\'s own data —');
lines.push('-- not against a fixed list derived from any other environment.');
lines.push('-- ============================================================================');
lines.push('\\set ON_ERROR_STOP on');
lines.push('\\if :{?do_commit} \\else \\set do_commit 0 \\endif');
lines.push('BEGIN;');
lines.push('SELECT ad_disable_triggers();');
lines.push('');
lines.push('CREATE TEMP TABLE etp4944_outcome (c_tax_id varchar(32) PRIMARY KEY, outcome text) ON COMMIT DROP;');
lines.push('');
lines.push('-- Proactively null parent_tax_id FROM the static sibling-overlap ids WHEN it');
lines.push('-- points AT a delete-attempt candidate. These 102 ids never get deleted (see');
lines.push('-- the static deactivation below) — they only ever get isactive/description');
lines.push('-- flipped — so nulling this metadata link is harmless. Skipping this step');
lines.push('-- would otherwise permanently block that candidate\'s delete for no good');
lines.push('-- reason, purely because a row that will survive anyway (just inactive) still');
lines.push('-- references it. Deliberately NOT applied to ids outside both sets (i.e. a');
lines.push('-- still-active KEEP rate) — if a live, user-facing rate references a');
lines.push('-- candidate as its parent, that candidate correctly falls back to deactivate');
lines.push('-- below; nulling a live rate\'s hierarchy link would be a real business-');
lines.push('-- meaning change, not a mechanical necessity, so it is left alone.');
lines.push('UPDATE c_tax SET parent_tax_id = NULL');
lines.push(`  WHERE c_tax_id = ANY(${pgArray(staticDeactivateIds)}) AND parent_tax_id = ANY(${pgArray(candidateIds)});`);
lines.push('');
lines.push('-- Per-id try-delete-then-fallback-to-deactivate, retried in a fixed-point');
lines.push('-- loop: candidates are NOT topologically pre-sorted by parentTaxRate, so on');
lines.push('-- a first pass a parent can fail merely because a SIBLING candidate that');
lines.push('-- references it hasn\'t been deleted yet — that is order-dependence, not a');
lines.push('-- real blocker. Each pass attempts only ids still unresolved; once a pass');
lines.push('-- makes zero further progress, whatever remains is genuinely blocked (by a');
lines.push('-- non-candidate reference, e.g. a live invoice line or a KEEP rate) and');
lines.push('-- falls back to deactivate. A nested BEGIN...EXCEPTION inside a PL/pgSQL DO');
lines.push('-- block gets an implicit savepoint from Postgres, so a caught exception');
lines.push('-- here does NOT abort the outer transaction. Catches ONLY');
lines.push('-- foreign_key_violation — anything else propagates and aborts the whole');
lines.push('-- script, since a genuinely unexpected error deserves a hard stop, not a');
lines.push('-- silent "must be safe to deactivate" misclassification.');
lines.push('DO $do4944$');
lines.push('DECLARE');
lines.push('  id varchar(32);');
lines.push(`  pending varchar(32)[] := ${pgArray(candidateIds)};`);
lines.push('  still_blocked varchar(32)[];');
lines.push('  made_progress boolean;');
lines.push('BEGIN');
lines.push('  LOOP');
lines.push('    still_blocked := ARRAY[]::varchar(32)[];');
lines.push('    made_progress := false;');
lines.push('    FOREACH id IN ARRAY pending LOOP');
lines.push('      BEGIN');
lines.push('        DELETE FROM obtl_tax_parameter WHERE c_tax_id = id;');
lines.push('        DELETE FROM c_tax_zone WHERE c_tax_id = id;');
lines.push('        DELETE FROM c_tax_trl WHERE c_tax_id = id;');
lines.push('        DELETE FROM c_tax_acct WHERE c_tax_id = id;');
lines.push("        DELETE FROM c_tax WHERE c_tax_id = id AND ad_client_id = '0';");
lines.push("        INSERT INTO etp4944_outcome VALUES (id, 'deleted');");
lines.push('        made_progress := true;');
lines.push('      EXCEPTION WHEN foreign_key_violation THEN');
lines.push('        still_blocked := array_append(still_blocked, id);');
lines.push('      END;');
lines.push('    END LOOP;');
lines.push('    EXIT WHEN array_length(still_blocked, 1) IS NULL OR NOT made_progress;');
lines.push('    pending := still_blocked;');
lines.push('  END LOOP;');
lines.push('  -- Whatever is still blocked after a full pass made zero progress is');
lines.push('  -- genuinely blocked (not just order-dependence) — deactivate it.');
lines.push('  FOREACH id IN ARRAY still_blocked LOOP');
lines.push(`    UPDATE c_tax SET isactive = 'N', description = '${esc(DISCARDED_DESCRIPTION)}' WHERE c_tax_id = id AND ad_client_id = '0';`);
lines.push("    INSERT INTO etp4944_outcome VALUES (id, 'deactivated (fk-blocked)');");
lines.push('  END LOOP;');
lines.push('END $do4944$;');
lines.push('');
lines.push('-- Static sibling-AEAT-module-overlap deactivation — never attempted as a');
lines.push('-- delete in the first place (see staticDeactivateIds in resolved-scope.json).');
lines.push(`UPDATE c_tax SET isactive = 'N', description = '${esc(DISCARDED_DESCRIPTION)}' WHERE c_tax_id = ANY(${pgArray(staticDeactivateIds)}) AND ad_client_id = '0';`);
lines.push(`INSERT INTO etp4944_outcome (c_tax_id, outcome) SELECT unnest(${pgArray(staticDeactivateIds)}), 'deactivated (sibling-module overlap)' ON CONFLICT (c_tax_id) DO NOTHING;`);
lines.push('');
lines.push('-- Dynamic parent-repoint: null out ONLY the parents that were ACTUALLY');
lines.push('-- deleted THIS run (read from etp4944_outcome, not a fixed dev-derived id');
lines.push('-- list) — a different environment may delete a different subset of the 145');
lines.push('-- candidates, so which parentTaxRate links need nulling can differ too.');
lines.push('UPDATE c_tax SET parent_tax_id = NULL');
lines.push("  WHERE parent_tax_id IN (SELECT c_tax_id FROM etp4944_outcome WHERE outcome = 'deleted');");
lines.push('');
lines.push(`-- MODIFY: rename ${modId} (unaffected by the dynamic split, unconditional)`);
lines.push(`UPDATE c_tax SET name = '${esc(newName)}', description = '${esc(newName)}' WHERE c_tax_id = '${modId}' AND ad_client_id = '0';`);
lines.push(`UPDATE c_tax_trl SET name = '${esc(newName)}' WHERE c_tax_id = '${modId}';`);
lines.push('');
lines.push('SELECT ad_enable_triggers();');
lines.push("\\echo ''");
lines.push("\\echo 'Outcome summary (delete vs. deactivate decided per-id, this run):'");
lines.push('SELECT outcome, count(*) FROM etp4944_outcome GROUP BY outcome ORDER BY outcome;');
lines.push('\\if :do_commit');
lines.push("  \\echo '>>> do_commit=1 : COMMITTING.'");
lines.push('  COMMIT;');
lines.push('\\else');
lines.push("  \\echo '>>> dry run : ROLLING BACK. Re-run with -v do_commit=1 to apply.'");
lines.push('  ROLLBACK;');
lines.push('\\endif');

const out = path.join(__dirname, '01-apply-tax-cleanup.sql');
fs.writeFileSync(out, lines.join('\n') + '\n');
console.log('Wrote', out, `(${candidateIds.length} delete-attempt candidates, ${staticDeactivateIds.length} static deactivate, 1 rename)`);

// --- Task 5: read-only, belt-and-suspenders usage check across the 145
// delete-attempt candidates (the 102 static-overlap ids are never attempted
// as deletes, so they don't need this check the same way). Independent of
// the FK-violation catch in 01-apply-tax-cleanup.sql — this catches tables
// WITHOUT an actual FK constraint, where an orphaned reference wouldn't
// throw at delete time but would silently break a report (VAT-book,
// fact_acct, gl_journalline-style business risk) instead. Emitted as
// separate individual SELECTs (not one combined UNION ALL) so a table
// that's missing on a given environment (e.g. the VAT-book/cash-VAT modules
// are optional) only blanks that one line instead of failing the whole
// check — this file sets ON_ERROR_STOP off for exactly that reason.
const usageLines = [];
usageLines.push('-- ETP-4944 — Read-only usage check. Run BEFORE 01-apply-tax-cleanup.sql on any target.');
usageLines.push('-- Any nonzero row below means that id is NOT safe to delete on this DB — escalate.');
usageLines.push('-- Covers the 145 delete-attempt candidates only (candidateIds) — the 102 static');
usageLines.push('-- sibling-overlap ids never get a delete attempt in the first place.');
usageLines.push('-- Some tables (VAT-book / cash-VAT: obirb_*, obcvat_*) only exist when their');
usageLines.push('-- owning module is installed — ON_ERROR_STOP is off so a missing table just');
usageLines.push('-- errors that one query instead of aborting the whole check.');
usageLines.push('\\set ON_ERROR_STOP off');
const USAGE_TABLES = [
  ['c_invoiceline', 'c_tax_id'], ['c_invoicetax', 'c_tax_id'], ['c_invoicelinetax', 'c_tax_id'],
  ['c_orderline', 'c_tax_id'], ['c_ordertax', 'c_tax_id'], ['c_orderlinetax', 'c_tax_id'],
  ['c_projectline', 'c_tax_id'], ['fact_acct', 'c_tax_id'], ['gl_journalline', 'c_tax_id'],
  ['c_tax_acct', 'c_tax_id'], ['c_taxregisterline', 'c_tax_id'], ['c_taxregister_type_lines', 'c_tax_id'],
  ['c_tax_report', 'c_tax_id'],
  // obirb_invbookline has NO `c_tax_id` column (confirmed empirically 2026-09-03
  // — the plan's original table list was wrong here) — it has two separate FKs,
  // c_tax_id_vat and c_tax_id_ec, both checked individually.
  ['obirb_invbookline', 'c_tax_id_vat'], ['obirb_invbookline', 'c_tax_id_ec'],
  ['obirb_invbooktax_setup', 'c_tax_id'],
  ['obcvat_manualsettlementline', 'c_tax_id'], ['ad_orginfo', 'c_tax_id'], ['c_bp_withholding', 'c_tax_id'],
  ['c_glitem', 'c_tax_id'], ['c_tax', 'parent_tax_id'], ['c_tax', 'c_taxbase_id'],
]; // full table list per scripts/etp-4177-tax-migration/README.md "Scope discovered"
const candidateInList = candidateIds.map(id => `'${id}'`).join(',');
for (const [t, c] of USAGE_TABLES) {
  usageLines.push(`\\echo '${t}.${c}:'`);
  usageLines.push(`SELECT count(*) FROM ${t} WHERE ${c} IN (${candidateInList});`);
}
fs.writeFileSync(path.join(__dirname, '00-assess-usage.sql'), usageLines.join('\n') + '\n');
console.log('Wrote', path.join(__dirname, '00-assess-usage.sql'), `(${candidateIds.length} candidate ids checked across ${USAGE_TABLES.length} table/column pairs)`);
