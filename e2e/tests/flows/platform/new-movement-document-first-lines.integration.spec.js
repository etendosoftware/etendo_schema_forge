import { test, expect } from '@playwright/test';
import { login, navigateTo } from '../../helpers/auth.js';
import { ensureProductSetup, PRODUCT_FIXTURE_ALPHA } from '../../helpers/product-helpers.js';
import {
  loadCredentials, waitForDetailReady,
  // Generic despite the name: any partner with an address, then the derived header
  // fields this document actually has. Aliased so the call sites read correctly.
  selectVendorBP as selectBusinessPartner,
  createDraftWithFirstLine, leaveNewDocumentThroughEmptyLines,
} from '../../helpers/purchase-helpers.js';

/**
 * New movement documents — the first lines are reachable without a manual save
 * (integration, live backend).
 *
 * A user creating a document fills the header and goes straight to the empty lines
 * state: "+ Añadir líneas" or an "Importar desde …" button, either of which saves the
 * header itself. The order, invoice and quotation specs cover that path for their own
 * windows (see CREATION_PATHS in purchase-helpers.js). These three documents had no
 * integration spec creating them from scratch at all — the specs that reach them
 * arrive through a document generated by a confirm or a return wizard — so nothing
 * would notice their empty state losing the action on an unsaved header.
 *
 * Each case starts on `/<spec>/new`, never clicks Guardar, and requires the action to
 * move to `/<spec>/<id>`:
 *   - goods shipment → "+ Añadir líneas" → the first product line persists;
 *   - customer return → "Importar desde albarán" → the shipment import opens;
 *   - return to vendor → "Añadir desde Albarán" → the receipt import opens.
 *
 * The two import cases stop at the open modal: which documents it lists depends on
 * the partner's history, and importing a line is covered elsewhere
 * (return-to-vendor-shipment.mocked.spec.js, ImportFromShipmentModal.spec.jsx).
 *
 * Gated by E2E_SALES_INTEGRATION=1, like the other sales/purchase document specs.
 */

const onboardingCreds = loadCredentials();
const RUN_INTEGRATION = process.env.E2E_SALES_INTEGRATION === '1';

/** Open `/<spec>/new` and fill the header with a business partner that has an address. */
async function openNewDocumentWithPartner(page, spec) {
  await navigateTo(page, spec);
  const newButton = page.getByTestId('action-new');
  await expect(newButton).toBeVisible({ timeout: 20_000 });
  await newButton.click();
  await waitForDetailReady(page);
  await selectBusinessPartner(page);
}

const IMPORT_CASES = [
  {
    label: 'customer return',
    spec: 'return-material-receipt',
    source: 'shipment',
    importTestId: 'action-import-shipment-empty-state',
  },
  {
    label: 'return to vendor',
    spec: 'return-to-vendor-shipment',
    source: 'receipt',
    importTestId: 'action-import-receipt-empty-state',
  },
];

test.describe('New movement documents — first lines without a manual save (integration)', () => {
  test.describe.configure({ timeout: 300_000 });

  test.skip(
    !RUN_INTEGRATION,
    'Set E2E_SALES_INTEGRATION=1 to run this live movement-document integration test.',
  );

  test.beforeEach(async ({ page }) => {
    await login(page, {
      user: onboardingCreds?.email || process.env.E2E_USER,
      password: onboardingCreds?.password || process.env.E2E_PASSWORD,
    });
    await expect(page, 'Login should redirect to /dashboard').toHaveURL(/dashboard/, { timeout: 30_000 });
  });

  test('goods shipment: the add-lines action saves the header and the first line persists', async ({ page }) => {
    // ETP-5079: a fresh tenant seeds no product, so the line needs its own fixture.
    await ensureProductSetup(page, PRODUCT_FIXTURE_ALPHA);
    await openNewDocumentWithPartner(page, 'goods-shipment');

    await createDraftWithFirstLine(page, {
      spec: 'goods-shipment', via: 'emptyState', productName: PRODUCT_FIXTURE_ALPHA.name,
    });
  });

  for (const { label, spec, source, importTestId } of IMPORT_CASES) {
    test(`${label}: importing from a ${source} saves the header and opens the import`, async ({ page }) => {
      await openNewDocumentWithPartner(page, spec);

      await leaveNewDocumentThroughEmptyLines(page, {
        spec, via: 'emptyState', trigger: page.getByTestId(importTestId),
      });

      // DetailView reopens the import after its save-and-navigate (route state
      // `openImportModal` → the empty state's `forceOpen`), on the saved record.
      await expect(page.getByTestId('import-lines-search'),
        `The ${source} import should open on the saved ${label}`,
      ).toBeVisible({ timeout: 15_000 });
    });
  }
});
